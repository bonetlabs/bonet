#!/usr/bin/env python3
"""Generate one XDP program per BONet global, so each can be verified on its own.

The kernel only verifies the globals a loaded program calls, so a global that no
example or test reaches is never checked. This script lists every
__bnt_*_g definition in the preprocessed XDP header and emits a program that
calls it once with zero arguments (ctx for the context, a zeroed stack buffer
for every other pointer).

usage: gen_programs.py OUT.c -- CLANG [CFLAGS...]
"""
import re
import subprocess
import sys

out_path = sys.argv[1]
cc = sys.argv[sys.argv.index('--') + 1:]
tu = '#include <linux/bpf.h>\n#include "bnt_xdp.h"\n'
pre = subprocess.run(cc + ['-E', '-P', '-x', 'c', '-'], input=tu, capture_output=True, text=True, check=True).stdout

protos = {}
for m in re.finditer(r'\bint\s+(__bnt_\w+_g)\s*\(([^)]*)\)\s*\{', pre):
    protos[m.group(1)] = [p.strip() for p in m.group(2).split(',')]
if not protos:
    sys.exit('no __bnt_*_g definitions found: is BNT_INLINE_ALL set?')

lines = ['/* Generated by gen_programs.py: one program per global. Do not edit. */',
         '#include <linux/bpf.h>', '#include <bpf/bpf_helpers.h>', '#include "bnt_xdp.h"', '']
for name, params in sorted(protos.items()):
    args = ['ctx' if 'struct xdp_md *' in p else '(void *)buf' if '*' in p else '0' for p in params]
    uses_buf = '(void *)buf' in args
    lines += [f'SEC("xdp") int c{name}(struct xdp_md *ctx)', '{']
    if uses_buf:
        lines.append('    __u64 buf[32] = {};')
    lines += [f'    return {name}({", ".join(args)}) ? XDP_DROP : XDP_PASS;', '}', '']
lines.append('char LICENSE[] SEC("license") = "GPL";')
with open(out_path, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print(f'{out_path}: {len(protos)} globals')
