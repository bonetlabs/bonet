#!/usr/bin/env python3
"""Generate one XDP program per case of cases.py.

Each program calls the global once with the case's arguments. Pointer
arguments point into bnt_res.out, a 256-byte global buffer prefilled with the
case's prefill; the global's return value goes to bnt_res.ret. run_case reads
both back from the program's .data map after BPF_PROG_TEST_RUN.

usage: gen_cases.py OUT_DIR   (writes case_<n>.c and cases.json)
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cases import CASES, CTX, OUT  # noqa: E402

out_dir = sys.argv[1]
os.makedirs(out_dir, exist_ok=True)
index = []
for n, (g, label, pkt, args, pre) in enumerate(CASES):
    cargs = []
    for a in args:
        if a == CTX:
            cargs.append('ctx')
        elif OUT <= a < OUT + 256:
            cargs.append(f'(void *)(bnt_res.out + {a - OUT})')
        else:
            cargs.append(f'{a & 0xffffffff:#x}')
    init = ', '.join(str(b) for b in pre) if pre else '0'
    src = f'''/* Generated by gen_cases.py: {g}/{label}. Do not edit. */
#include <linux/bpf.h>
#include <bpf/bpf_helpers.h>
#include "bnt_xdp.h"

struct bnt_case_res {{
    __u8 out[256];
    int ret;
}} __attribute__((aligned(8)));

struct bnt_case_res bnt_res = {{ .out = {{ {init} }}, .ret = -999 }};

SEC("xdp") int run(struct xdp_md *ctx)
{{
    bnt_res.ret = __bnt_{g}_g({', '.join(cargs)});
    return XDP_PASS;
}}

char LICENSE[] SEC("license") = "GPL";
'''
    with open(os.path.join(out_dir, f'case_{n}.c'), 'w') as f:
        f.write(src)
    index.append(dict(n=n, name=f'{g}/{label}', g=g, pkt=pkt.hex()))
with open(os.path.join(out_dir, 'cases.json'), 'w') as f:
    json.dump(index, f)
print(f'{out_dir}: {len(index)} cases')
