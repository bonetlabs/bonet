#!/usr/bin/env python3
"""Generate one XDP program per public bnt_<hdr>__<name> API of bnt_xdp.h.

Each program calls its API once, with every argument read at run time from the
global `io` (struct bnt_api_io in api_io.h), so that clang cannot fold the
wrapper's checks away: a case sets the arguments, the view offsets and which
pointers are NULL before BPF_PROG_TEST_RUN, and reads back the return value,
the buffers and the views afterwards.

Parameter k of the API gets:
  struct xdp_md *       the program's context
  bnt_<hdr> *           a view {ctx, io.off[k]}; after the call its offset goes
                        to io.vout[k][0] and whether its ctx is set to [1]
  any other pointer     io.buf[k] (input, output, or both)
  a scalar              io.arg[k]
An API returning a pointer (the fib MAC getters) has the 6 bytes it points to
copied to io.buf[1], and io.ret set to whether it is not NULL.
A pointer parameter is NULL when bit k of io.nullmask is set.

usage: gen_programs.py OUT_DIR -- CLANG [CFLAGS...]
       (writes <api>.c for every API, and apis.json with their signatures)
"""
import json
import os
import re
import subprocess
import sys

VIEWS = {'eth', 'ipv4', 'ipv6', 'tcp', 'udp', 'icmp4', 'icmp6', 'arp', 'mpls'}


def signatures(cc):
    tu = '#include <linux/bpf.h>\n#include "bnt_xdp.h"\n'
    pre = subprocess.run(cc + ['-E', '-P', '-x', 'c', '-'], input=tu, capture_output=True, text=True,
                         check=True).stdout
    apis = {}
    for m in re.finditer(r'static\s+(?:__inline__\s+|inline\s+|__attribute__\(\([^)]*\)\)\s*)*'
                         r'([\w ]+?\**)\s*\b(bnt_[a-z0-9]+__\w+)\s*\(([^)]*)\)\s*\{', pre):
        ret, name, params = m.groups()
        ps = []
        for p in params.split(','):
            p = p.strip()
            t = re.sub(r'\b\w+(\[\d+\])?$', lambda a: '*' if a.group(1) else '', p).strip()
            ps.append(' '.join(t.split()))
        apis[name] = dict(ret=ret.strip(), params=ps)
    return apis


def kind(t):
    if t == 'struct xdp_md *':
        return 'ctx', None
    m = re.fullmatch(r'(?:const )?bnt_(\w+) \*', t)
    if m and m.group(1) in VIEWS:
        return 'view', 'bnt_' + m.group(1)
    if t.endswith('*'):
        return 'ptr', None
    return 'arg', None


def nullable(k):
    # The barrier hides where the pointer comes from: otherwise clang tests all
    # the NULL bits at once and keeps dead loads through the NULL pointer,
    # which the verifier cannot tell are dead.
    return [f'    if (io.nullmask & {1 << k})', f'        p{k} = NULL;', f'    asm volatile("" : "+r"(p{k}));']


def program(name, sig):
    body, args = [], []
    for k, t in enumerate(sig['params']):
        what, vt = kind(t)
        if what == 'ctx':
            args.append('ctx')
        elif what == 'view':
            body.append(f'    {vt} v{k} = {{ ctx, io.off[{k}] }}, *p{k} = &v{k};')
            body += nullable(k)
            args.append(f'p{k}')
        elif what == 'ptr':
            body.append(f'    void *p{k} = io.buf[{k}];')
            body += nullable(k)
            args.append(f'p{k}')
        else:
            args.append(f'({t})io.arg[{k}]')
    if sig['ret'].endswith('*'):  # a MAC inside a view-less struct: copy it to buf[1]
        body += [f'    const unsigned char *r = {name}({", ".join(args)});',
                 '    io.ret = r != NULL;', '    if (r)', '        __builtin_memcpy(io.buf[1], r, 6);']
    else:
        body.append(f'    io.ret = (int){name}({", ".join(args)});')
    if 'ctx' not in ''.join(body + args):
        body.insert(0, '    (void)ctx;')
    for k, t in enumerate(sig['params']):
        if kind(t)[0] == 'view':
            body.append(f'    io.vout[{k}][0] = v{k}.__off;')
            body.append(f'    io.vout[{k}][1] = v{k}.__ctx == ctx;')
    return f'''/* Generated by gen_programs.py: {name}. Do not edit. */
#include <linux/bpf.h>
#include <bpf/bpf_helpers.h>
#include "bnt_xdp.h"
#include "api_io.h"

struct bnt_api_io io = {{ .ret = -999 }};

SEC("xdp") int run(struct xdp_md *ctx)
{{
{chr(10).join(body)}
    return XDP_PASS;
}}

char LICENSE[] SEC("license") = "GPL";
'''


def main():
    out = sys.argv[1]
    apis = signatures(sys.argv[sys.argv.index('--') + 1:])
    if not apis:
        sys.exit('no bnt_*__* API found')
    os.makedirs(out, exist_ok=True)
    for name, sig in apis.items():
        if len(sig['params']) > 4:
            sys.exit(f'{name}: more than 4 parameters, extend struct bnt_api_io')
        path = os.path.join(out, name + '.c')
        src = program(name, sig)
        if not os.path.exists(path) or open(path).read() != src:  # keep make's timestamps
            with open(path, 'w') as f:
                f.write(src)
    with open(os.path.join(out, 'apis.json'), 'w') as f:
        json.dump(apis, f, indent=1, sort_keys=True)
    print(f'{out}: {len(apis)} APIs')


main()
