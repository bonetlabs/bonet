#!/usr/bin/env python3
"""Write src/bnt_asm_globals.h from the per-global choices.

Each global's body is the code of the configuration chosen for it, taken from
that configuration's object (candidates.py) and printed as clang BPF assembly
(bpfasm.py). Its prototype is the C one, so the BTF keeps the parameter names.
The header refuses to build with settings the asm was not built for.

usage: gen_asm.py CHOICES OBJ_DIR [OUT]
  CHOICES  lines "global: config", as the selection copies them
           (data/choices-kernel7.0.txt)
  OBJ_DIR  candidates.py output, with <config>.o
  OUT      default: src/bnt_asm_globals.h
"""
import os
import re
import subprocess
import sys

from bpfasm import Elf, function

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
# Settings that change the globals' code (checked by building with each one
# changed); the asm is valid only with their defaults.
KNOBS = ['BNT_XDP_MAX_PACKET_OFFSET', 'BNT_XDP_MAX_HEADER_PREFIX', 'BNT_MAX_VLAN_DEPTH',
         'BNT_MAX_IPV6_EXT_DEPTH', 'BNT_SRV6_MAX_SEGS', 'BNT_CSUM_CHUNK', 'BNT_MAX_PAYLOAD',
         'BNT_ICMP6_ND_NEIGHBOR_ADVERT', 'BNT_ICMP6_ND_ROUTER_ADVERT']

choices_path, objdir = sys.argv[1:3]
out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(REPO, 'src', 'bnt_asm_globals.h')
choice = {}
for line in open(choices_path):
    if ':' in line:
        g, c = line.split(':', 1)
        choice[f'__bnt_{g.strip()}_g'] = c.split('(')[0].strip()

# The C definitions, from bnt_xdp.h with the asm turned off.
cc = ['clang-20', '-target', 'bpf', '-mcpu=v3', '-D__TARGET_ARCH_x86', '-DBNT_ASM_GLOBALS=0',
      f'-I{REPO}/src', f'-I/usr/include/{os.uname().machine}-linux-gnu', '-x', 'c', '-']
tu = '#include <linux/bpf.h>\n#include "bnt_xdp.h"\n'
pre = subprocess.run(cc + ['-E', '-P'], input=tu, check=True, capture_output=True, text=True).stdout
macros = subprocess.run(cc + ['-E', '-dM'], input=tu, check=True, capture_output=True, text=True).stdout


def match(s, i):
    d = 0
    for j in range(i, len(s)):
        d += {'(': 1, ')': -1}.get(s[j], 0)
        if d == 0:
            return j
    raise ValueError(i)


protos = {}
for m in re.finditer(r'\bint\s+(__bnt_\w+_g)\s*\(', pre):
    j = match(pre, m.end() - 1)
    if re.match(r'\s*\{', pre[j + 1:]):
        protos[m.group(1)] = re.sub(r'\s+', ' ', pre[m.start():j + 1])
missing = set(protos) ^ set(choice)
if missing:
    sys.exit(f'globals without a choice, or chosen but unknown: {sorted(missing)}')


def asm_line(line):
    code, _, note = line.partition(' /* ')
    return f'        "{code}\\n"' + (f'  /* {note}' if note else '')


elfs, defs = {}, []
for g in sorted(choice):
    c = choice[g]
    if c not in elfs:
        elfs[c] = Elf(os.path.join(objdir, c + '.o'))
    lines = function(elfs[c], g, f'bnt{g[5:-2]}')
    # The last exit is the compiler's: anything clang emits after an asm
    # that exits by itself is unreachable, and the verifier rejects it. So the
    # chosen code has to end with exit; it is never rearranged.
    if lines[-1] != 'exit':
        sys.exit(f'{g}: the code of {c} does not end with exit; choose a configuration whose code does')
    body = '\n'.join(asm_line(line) for line in lines[:-1])
    defs.append(f'/* {g[6:-2]}: {c} */\n__attribute__((noinline, weak, nonnull(1))) {protos[g]}\n{{\n'
                f'    register long r0 asm("r0");\n\n'
                f'    asm volatile(\n{body}\n        : "=r"(r0));\n    return r0;\n}}\n')


def default(k):
    m = re.search(rf'^#define {k} (.*)$', macros, re.M)
    return m.group(1).strip()


guards = ''.join(f'#if {k} != {default(k)}\n#error "{k} is not {default(k)}: the asm globals need the default; '
                 f'build with -DBNT_ASM_GLOBALS=0"\n#endif\n' for k in KNOBS)
open(out, 'w').write(f'''/* SPDX-License-Identifier: MIT */
/*
 * Generated by validation/exec_metrics/gen_asm.py from
 * validation/exec_metrics/data/{os.path.basename(choices_path)}. Do not edit.
 *
 * The XDP globals as BPF assembly: each body is the code of the configuration
 * named above it, as that compiler (and optimizer) produced it. Included by
 * bnt_xdp.h in global mode when BNT_ASM_GLOBALS is set.
 */
#ifndef BNT_ASM_GLOBALS_H
#define BNT_ASM_GLOBALS_H

#if BNT_STRICT_ALIGN || __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__
#error "the asm globals are built for little-endian targets with unaligned packet access; build with -DBNT_ASM_GLOBALS=0"
#endif
{guards}
/* Each body ends where its last exit was: the compiler emits that one, after
 * the asm, returning r0. The parameters are only read by the asm. */
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wunused-parameter"

{chr(10).join(defs)}
#pragma clang diagnostic pop

#endif /* BNT_ASM_GLOBALS_H */
''')
print(f'{out}: {len(defs)} globals')
